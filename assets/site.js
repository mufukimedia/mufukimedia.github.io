/* ---------- Home: video + tracking stage light ---------- */
function initHero() {
  const heroEl = $("hero");
  if (!heroEl) return;
  const video = $("heroVideo");
  if (CONFIG.heroVideo && video) {
    video.src = CONFIG.heroVideo;
    video.hidden = false;
    $("heroShade").hidden = false;
    video.addEventListener("error", () => { video.hidden = true; $("heroShade").hidden = true; });
    if (!reduceMotion) { video.autoplay = true; video.play().catch(() => {}); }
  }
  const beam = $("trackBeam");
  const pool = $("spotPool");
  let w = 0, h = 0, cx = 0, cy = 0, tx = 0, ty = 0, pointerActive = false, visible = true, start = performance.now();
  function size() {
    const r = heroEl.getBoundingClientRect();
    w = r.width; h = r.height;
    if (!cx) { cx = tx = w * 0.32; cy = ty = h * 0.62; }
  }
  function draw() {
    const pw = pool.offsetWidth, ph = pool.offsetHeight;
    pool.style.transform = `translate(${cx - pw / 2}px, ${cy - ph / 2}px)`;
    const ox = w * 0.5, half = pw * 0.42;
    beam.style.clipPath = `polygon(${ox - 14}px 0px, ${ox + 14}px 0px, ${cx + half}px ${cy}px, ${cx - half}px ${cy}px)`;
  }
  function frame(now) {
    if (!pointerActive && !reduceMotion) {
      const s = (now - start) / 1000;
      tx = w * (0.34 + 0.22 * Math.sin(s * 0.35));
      ty = h * (0.6 + 0.06 * Math.sin(s * 0.6));
    }
    cx += (tx - cx) * 0.08; cy += (ty - cy) * 0.08;
    draw();
    if (visible && !reduceMotion) requestAnimationFrame(frame);
  }
  size(); draw();
  addEventListener("resize", () => { size(); draw(); });
  if (reduceMotion) return;
  heroEl.addEventListener("pointermove", e => {
    if (e.pointerType === "touch") return;
    const r = heroEl.getBoundingClientRect();
    tx = e.clientX - r.left; ty = e.clientY - r.top; pointerActive = true;
  });
  heroEl.addEventListener("pointerleave", () => { pointerActive = false; start = performance.now(); });
  new IntersectionObserver(([en]) => {
    const was = visible; visible = en.isIntersecting;
    if (visible && !was) requestAnimationFrame(frame);
  }).observe(heroEl);
  requestAnimationFrame(frame);
}

